using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using ArrowMaze.LevelContent;
using UnityEditor;
using UnityEngine;

namespace ArrowMaze.EditorTools
{
    public static class LevelValidationMenu
    {
        private sealed class Entry
        {
            public string RelativePath;
            public string ExpectedName;
            public LevelDefinition Level;
            public LevelValidationResult Validation;
            public string ParseError;
        }

        [MenuItem("ArrowMaze/Validate Current Levels")]
        public static void ValidateCurrentLevels()
        {
            string projectRoot = Directory.GetCurrentDirectory();
            string levelsRoot = Path.Combine(Application.dataPath, "Resources", "Levels");
            string reportPath = Path.Combine(projectRoot, "Research", "From APK", "Codex", "current_level_validation_report.md");

            List<Entry> entries = ValidateLevelFolder(levelsRoot);
            string markdown = BuildReport(entries, levelsRoot);

            Directory.CreateDirectory(Path.GetDirectoryName(reportPath));
            File.WriteAllText(reportPath, markdown);
            AssetDatabase.Refresh();

            int errorCount = entries.Sum(entry => entry.Validation != null ? entry.Validation.ErrorCount : 1);
            int warningCount = entries.Sum(entry => entry.Validation != null ? entry.Validation.WarningCount : 0);
            EditorUtility.DisplayDialog(
                "ArrowMaze Level Validation",
                "Validated " + entries.Count + " level files.\nErrors: " + errorCount + "\nWarnings: " + warningCount + "\n\nReport:\n" + reportPath,
                "OK");
        }

        private static List<Entry> ValidateLevelFolder(string levelsRoot)
        {
            var entries = new List<Entry>();
            if (!Directory.Exists(levelsRoot))
            {
                return entries;
            }

            string[] files = Directory.GetFiles(levelsRoot, "*.json", SearchOption.AllDirectories);
            Array.Sort(files, StringComparer.OrdinalIgnoreCase);

            foreach (string file in files)
            {
                string json = File.ReadAllText(file);
                string expectedName = Path.GetFileNameWithoutExtension(file);
                var entry = new Entry
                {
                    RelativePath = ToProjectRelativePath(file),
                    ExpectedName = expectedName
                };

                var parsed = LevelJsonSerializer.FromCurrentJson(json);
                if (!parsed.IsSuccess)
                {
                    entry.ParseError = parsed.Error;
                    entry.Validation = new LevelValidationResult();
                    entry.Validation.AddError("parse_failed", parsed.Error);
                }
                else
                {
                    entry.Level = parsed.Value;
                    entry.Validation = LevelValidator.Validate(parsed.Value, expectedName);
                }

                entries.Add(entry);
            }

            return entries;
        }

        private static string BuildReport(List<Entry> entries, string levelsRoot)
        {
            int errorCount = entries.Sum(entry => entry.Validation != null ? entry.Validation.ErrorCount : 1);
            int warningCount = entries.Sum(entry => entry.Validation != null ? entry.Validation.WarningCount : 0);
            int validCount = entries.Count(entry => entry.Validation != null && entry.Validation.IsValid);

            var sb = new StringBuilder();
            sb.AppendLine("# ArrowMaze Current Level Validation Report");
            sb.AppendLine();
            sb.AppendLine("Generated by Unity menu: `ArrowMaze/Validate Current Levels`.");
            sb.AppendLine();
            sb.AppendLine("Level folder: `" + ToProjectRelativePath(levelsRoot) + "`");
            sb.AppendLine();
            sb.AppendLine("## Summary");
            sb.AppendLine();
            sb.AppendLine("- Files checked: `" + entries.Count + "`");
            sb.AppendLine("- Valid files: `" + validCount + "`");
            sb.AppendLine("- Errors: `" + errorCount + "`");
            sb.AppendLine("- Warnings: `" + warningCount + "`");
            sb.AppendLine();
            sb.AppendLine("## File Results");
            sb.AppendLine();
            sb.AppendLine("| File | Name | Size | Snakes | Errors | Warnings | Result |");
            sb.AppendLine("|---|---:|---:|---:|---:|---:|---|");

            foreach (Entry entry in entries)
            {
                string name = entry.Level != null ? entry.Level.Name : "";
                string size = entry.Level != null ? entry.Level.Width + "x" + entry.Level.Height : "";
                string snakes = entry.Level != null && entry.Level.Snakes != null ? entry.Level.Snakes.Count.ToString() : "0";
                string result = entry.Validation != null && entry.Validation.IsValid ? "PASS" : "FAIL";
                int errors = entry.Validation != null ? entry.Validation.ErrorCount : 1;
                int warnings = entry.Validation != null ? entry.Validation.WarningCount : 0;

                sb.AppendLine("| `" + entry.RelativePath + "` | `" + name + "` | `" + size + "` | `" + snakes + "` | `" + errors + "` | `" + warnings + "` | " + result + " |");
            }

            sb.AppendLine();
            sb.AppendLine("## Issues");
            sb.AppendLine();

            foreach (Entry entry in entries)
            {
                if (entry.Validation == null || entry.Validation.Issues.Count == 0)
                {
                    continue;
                }

                sb.AppendLine("### `" + entry.RelativePath + "`");
                sb.AppendLine();
                foreach (LevelValidationIssue issue in entry.Validation.Issues)
                {
                    sb.AppendLine("- `" + issue.Severity + "` `" + issue.Code + "`: " + issue.Message);
                }
                sb.AppendLine();
            }

            return sb.ToString();
        }

        private static string ToProjectRelativePath(string path)
        {
            string projectRoot = Directory.GetCurrentDirectory();
            string fullPath = Path.GetFullPath(path);
            if (fullPath.StartsWith(projectRoot, StringComparison.OrdinalIgnoreCase))
            {
                return fullPath.Substring(projectRoot.Length).TrimStart(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar).Replace('\\', '/');
            }

            return path.Replace('\\', '/');
        }
    }
}

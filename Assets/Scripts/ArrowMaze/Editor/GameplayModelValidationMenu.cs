using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using ArrowMaze.Common;
using ArrowMaze.Gameplay.Board;
using ArrowMaze.Gameplay.Snakes;
using ArrowMaze.LevelContent;
using UnityEditor;
using UnityEngine;

namespace ArrowMaze.EditorTools
{
    public static class GameplayModelValidationMenu
    {
        private sealed class Entry
        {
            public string RelativePath;
            public string LevelName;
            public int Width;
            public int Height;
            public int SnakeCount;
            public int LegalFirstMoves;
            public int BlockedFirstMoves;
            public string Error;
        }

        [MenuItem("ArrowMaze/Validate Gameplay Model")]
        public static void ValidateGameplayModel()
        {
            string projectRoot = Directory.GetCurrentDirectory();
            string levelsRoot = Path.Combine(Application.dataPath, "Resources", "Levels");
            string reportPath = Path.Combine(projectRoot, "Research", "From APK", "Codex", "gameplay_model_validation_report.md");

            List<Entry> entries = ValidateLevels(levelsRoot);
            string markdown = BuildReport(entries, levelsRoot);

            Directory.CreateDirectory(Path.GetDirectoryName(reportPath));
            File.WriteAllText(reportPath, markdown);
            AssetDatabase.Refresh();

            int errors = entries.Count(entry => !string.IsNullOrEmpty(entry.Error));
            EditorUtility.DisplayDialog(
                "ArrowMaze Gameplay Model Validation",
                "Checked " + entries.Count + " level files.\nErrors: " + errors + "\n\nReport:\n" + reportPath,
                "OK");
        }

        private static List<Entry> ValidateLevels(string levelsRoot)
        {
            var entries = new List<Entry>();
            if (!Directory.Exists(levelsRoot))
            {
                return entries;
            }

            string[] files = Directory.GetFiles(levelsRoot, "*.json", SearchOption.AllDirectories);
            Array.Sort(files, StringComparer.OrdinalIgnoreCase);

            foreach (string file in files)
            {
                entries.Add(ValidateFile(file));
            }

            return entries;
        }

        private static Entry ValidateFile(string file)
        {
            var entry = new Entry
            {
                RelativePath = ToProjectRelativePath(file)
            };

            string json = File.ReadAllText(file);
            Result<LevelDefinition> levelResult = LevelJsonSerializer.FromCurrentJson(json);
            if (!levelResult.IsSuccess)
            {
                entry.Error = levelResult.Error;
                return entry;
            }

            LevelDefinition level = levelResult.Value;
            entry.LevelName = level.Name;
            entry.Width = level.Width;
            entry.Height = level.Height;
            entry.SnakeCount = level.Snakes != null ? level.Snakes.Count : 0;

            LevelValidationResult validation = LevelValidator.Validate(level, Path.GetFileNameWithoutExtension(file));
            if (!validation.IsValid)
            {
                entry.Error = "Level validation failed with " + validation.ErrorCount + " error(s).";
                return entry;
            }

            Result<BoardModel> boardResult = BoardFactory.Create(level);
            if (!boardResult.IsSuccess)
            {
                entry.Error = boardResult.Error;
                return entry;
            }

            BoardModel board = boardResult.Value;
            foreach (SnakeModel snake in board.Snakes)
            {
                SnakeMoveResult move = MoveValidator.Validate(board, snake);
                if (move.Status == SnakeMoveStatus.CanEscape)
                {
                    entry.LegalFirstMoves++;
                }
                else if (move.Status == SnakeMoveStatus.Blocked)
                {
                    entry.BlockedFirstMoves++;
                }
            }

            if (entry.SnakeCount > 0 && entry.LegalFirstMoves == 0)
            {
                entry.Error = "No legal first move found by gameplay model.";
            }

            return entry;
        }

        private static string BuildReport(List<Entry> entries, string levelsRoot)
        {
            int errors = entries.Count(entry => !string.IsNullOrEmpty(entry.Error));

            var sb = new StringBuilder();
            sb.AppendLine("# ArrowMaze Gameplay Model Validation Report");
            sb.AppendLine();
            sb.AppendLine("Generated by Unity menu: `ArrowMaze/Validate Gameplay Model`.");
            sb.AppendLine();
            sb.AppendLine("Level folder: `" + ToProjectRelativePath(levelsRoot) + "`");
            sb.AppendLine();
            sb.AppendLine("## Summary");
            sb.AppendLine();
            sb.AppendLine("- Files checked: `" + entries.Count + "`");
            sb.AppendLine("- Errors: `" + errors + "`");
            sb.AppendLine();
            sb.AppendLine("## File Results");
            sb.AppendLine();
            sb.AppendLine("| File | Name | Size | Snakes | Legal First Moves | Blocked First Moves | Result |");
            sb.AppendLine("|---|---:|---:|---:|---:|---:|---|");

            foreach (Entry entry in entries)
            {
                string result = string.IsNullOrEmpty(entry.Error) ? "PASS" : "FAIL: " + entry.Error;
                sb.AppendLine("| `" + entry.RelativePath + "` | `" + entry.LevelName + "` | `" + entry.Width + "x" + entry.Height + "` | `" + entry.SnakeCount + "` | `" + entry.LegalFirstMoves + "` | `" + entry.BlockedFirstMoves + "` | " + result + " |");
            }

            return sb.ToString();
        }

        private static string ToProjectRelativePath(string path)
        {
            string projectRoot = Directory.GetCurrentDirectory();
            string fullPath = Path.GetFullPath(path);
            if (fullPath.StartsWith(projectRoot, StringComparison.OrdinalIgnoreCase))
            {
                return fullPath.Substring(projectRoot.Length).TrimStart(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar).Replace('\\', '/');
            }

            return path.Replace('\\', '/');
        }
    }
}
